CREATE DATABASE IF NOT EXISTS campuspro CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE campuspro;

CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('student','faculty','admin') NOT NULL DEFAULT 'student',
 department VARCHAR(100) NOT NULL DEFAULT 'CSE',
 is_active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS projects (
 id INT AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(200) NOT NULL,
 abstract TEXT NOT NULL,
 tech_stack VARCHAR(255) DEFAULT '',
 owner_id INT NOT NULL,
 project_link VARCHAR(2048) DEFAULT NULL,
 image_paths LONGTEXT DEFAULT NULL,
 status ENUM('Submitted','Under Review','Approved','Needs Changes') NOT NULL DEFAULT 'Submitted',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_projects_owner FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
